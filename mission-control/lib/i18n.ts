'use client';
import { create } from 'zustand';
import { persist } from 'zustand/middleware';

export type Lang = 'de' | 'en';

interface LangStore {
  lang: Lang;
  setLang: (l: Lang) => void;
  toggleLang: () => void;
}

export const useLangStore = create<LangStore>()(
  persist(
    (set) => ({
      lang: 'de',
      setLang: (l) => set({ lang: l }),
      toggleLang: () => set((s) => ({ lang: s.lang === 'de' ? 'en' : 'de' })),
    }),
    { name: 'trinity-lang' }
  )
);

