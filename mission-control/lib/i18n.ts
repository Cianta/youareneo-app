export function useT() {
  const lang = useLangStore(s => s.lang);
  return (de: string): string => (lang === 'en' ? (EN[de] ?? de) : de);
}

/** BCP-47 locale matching the active UI language — for date/time formatting. */
export function useLocale(): string {
  const lang = useLangStore(s => s.lang);
  return lang === 'en' ? 'en-US' : 'de-DE';
}
